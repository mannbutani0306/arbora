"""Publish evaluation rows to Supabase without exposing or tracking service credentials."""

from __future__ import annotations

import argparse
import os
import subprocess
from pathlib import Path
from typing import Any

from supabase import create_client


def load_local_env(path: Path) -> None:
    """Load simple KEY=VALUE pairs without logging their contents."""
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip("'\""))


def warn_if_secret_tracked(root: Path, secret: str) -> None:
    """Loudly fail if the active service-role key appears in any tracked text file."""
    tracked = subprocess.run(
        ["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True
    ).stdout.decode("utf-8", errors="replace").split("\0")
    matches: list[str] = []
    for filename in tracked:
        if not filename:
            continue
        path = root / filename
        if not path.is_file() or path.stat().st_size > 5_000_000:
            continue
        try:
            if secret in path.read_text(encoding="utf-8"):
                matches.append(filename)
        except (UnicodeDecodeError, OSError):
            continue
    if matches:
        print("\n" + "!" * 78)
        print("SECURITY WARNING: SUPABASE SERVICE ROLE KEY FOUND IN TRACKED FILE(S)")
        print("Remove the secret and rotate it immediately: " + ", ".join(matches))
        print("!" * 78 + "\n")
        raise RuntimeError("Refusing to publish while the service key is tracked.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", nargs="+", required=True)
    parser.add_argument("--dataset", default="test")
    parser.add_argument("--config", default="")
    parser.add_argument("--notes", default="Metrics generated by Arbora's reproducible evaluation pipeline.")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    load_local_env(root / "ml" / ".env")
    url = os.environ.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_ROLE_KEY")
    if not url or not key:
        raise SystemExit("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in ml/.env.")
    warn_if_secret_tracked(root, key)
    client = create_client(url, key)
    rows: list[dict[str, Any]] = []
    for filename in args.results:
        result = __import__("json").loads(Path(filename).read_text(encoding="utf-8"))
        task = str(result["task"])
        rows.append({
            "model_name": str(result["model"]),
            "task": task,
            "dataset": args.dataset,
            "n_test": int(result.get("n_test", result.get("metrics", {}).get("n_test", 0))),
            "metrics": result.get("metrics", {}),
            "by_error_type": result.get("by_error_type", {}),
            "by_length_bucket": result.get("by_size_bucket", {}),
            "config": args.config,
            "notes": args.notes,
        })
    response = client.table("model_evaluations").insert(rows).execute()
    print(f"Published {len(response.data)} evaluation row(s).")


if __name__ == "__main__":
    main()
